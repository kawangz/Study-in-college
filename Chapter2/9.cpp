#include <iostream>
using namespace std;

int main() {
    cout << "The amount of memory of char: " << sizeof(char) <<" bytes" << endl;
    cout << "The amount of memory of int: " << sizeof(int) <<" bytes" << endl;
    cout << "The amount of memory of float: " << sizeof(float) <<" bytes" << endl;
    cout << "The amount of memory of double: " << sizeof(double) <<" bytes"<< endl;
    
    return 0;
}